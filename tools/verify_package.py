"""
Verifies this package (read-only; changes nothing).

Checks:
  1. Every file listed in manifests/PACKAGE_FILES.sha256 is present and unchanged (files added later, such as
     new runs or a regenerated run_code/, are reported separately and are not failures).
  2. original_code/ matches manifests/original_code_distribution.sha256 (the 19 distribution copies).
  3. run_code/ is exactly what tools/make_run_copies.py produces from original_code/ for the root recorded in
     run_code/_generated_for.json, i.e. the execution copies differ from the originals only in path strings
     (checked line by line, and by Python syntax tree after normalisation of the permitted path-string literals).
  4. With --check_excluded: files that are not shipped but were regenerated by a new run
     (manifests/excluded_files.sha256) are compared by SHA-256 with the verified run.

Usage (from the package folder):  python tools/verify_package.py [--check_excluded]
"""
import argparse
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.dont_write_bytecode = True  # do not add __pycache__ to the package


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def sha_list(p: Path) -> dict:
    out = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if line.strip():
            h, rel = line.split("  ", 1)
            out[rel] = h
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check_excluded", action="store_true")
    args = ap.parse_args()
    fails, notes = [], []
    listed = sha_list(REPO / "manifests" / "PACKAGE_FILES.sha256")
    run_code_regenerated = False
    gen = REPO / "run_code" / "_generated_for.json"
    for rel, h in listed.items():
        p = REPO / rel
        if not p.is_file():
            fails.append(f"missing: {rel}")
        elif sha256(p) != h:
            if rel.startswith("run_code/"):
                run_code_regenerated = True  # allowed: checked in step 3
            else:
                fails.append(f"changed: {rel}")
    on_disk = sorted(q.relative_to(REPO).as_posix() for q in REPO.rglob("*") if q.is_file())
    extra = [r for r in on_disk if r not in listed and r != "manifests/PACKAGE_FILES.sha256"]
    if run_code_regenerated:
        notes.append("run_code/ has been regenerated for this folder (checked below)")
    for rel, h in sha_list(REPO / "manifests" / "original_code_distribution.sha256").items():
        if not (REPO / rel).is_file() or sha256(REPO / rel) != h:
            fails.append(f"original_code copy changed: {rel}")
    spec = importlib.util.spec_from_file_location("mrc", REPO / "tools" / "make_run_copies.py")
    mrc = importlib.util.module_from_spec(spec); spec.loader.exec_module(mrc)
    g = json.loads(gen.read_text(encoding="utf-8"))
    try:
        files, changes = mrc.generate(REPO / "original_code", mrc.PLACEHOLDER_USER, g["repo_root"], g["brfss_xpt"], g["style"])
        for n, b in files.items():
            if (REPO / "run_code" / n).read_bytes() != b:
                fails.append(f"run_code/{n} is not the path-only copy of its original")
        notes.append(f"run_code/: {len(files)} copies = original_code/ with {len(changes)} path lines rewritten "
                     f"for {g['repo_root']} ({g['style']})")
    except SystemExit as e:
        fails.append(f"run_code check stopped: {e}")
    exc_report = {}
    if args.check_excluded:
        for rel, h in sha_list(REPO / "manifests" / "excluded_files.sha256").items():
            p = REPO / rel
            exc_report[rel] = "not regenerated" if not p.is_file() else ("IDENTICAL" if sha256(p) == h else "DIFFERS")
    report = {"listed_files_checked": len(listed), "files_added_since_packaging": len(extra),
              "notes": notes, "excluded_files": exc_report or "not checked (use --check_excluded)",
              "result": "PASS" if not fails else "FAIL", "failures": fails}
    print(json.dumps(report, indent=2))
    sys.exit(0 if not fails else 1)


if __name__ == "__main__":
    main()
